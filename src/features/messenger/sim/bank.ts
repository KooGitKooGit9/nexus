/**
 * A reply line. `r` restricts it to roles, `who` to specific users, `tag` remembers what was suggested
 * (e.g. a menu) so later teammates can agree with it. `|` splits a line into consecutive bubbles.
 */
export type Line =
  | string
  | {
      t: string
      r?: Role[]
      who?: string[]
      not?: string[]
      tag?: string
      /** never the first answer (e.g. declines) */
      alt?: boolean
      /** only in a 1:1 DM ('dm') or only in a channel / group ('room') */
      ctx?: 'dm' | 'room'
    }

